-- 1. Three ways to define a primary key
-- Method 1: column-level constraint
CREATE TABLE students_m1 (
    student_id INTEGER PRIMARY KEY,
    name VARCHAR(100),
    email VARCHAR(150)
);
-- Method 2: table-level constraint
CREATE TABLE students_m2 (
    student_id INTEGER,
    name VARCHAR(100),
    email VARCHAR(150),
    PRIMARY KEY (student_id)
);
-- Method 3: named constraint
CREATE TABLE students_m3 (
    student_id INTEGER,
    name VARCHAR(100),
    email VARCHAR(150),
    CONSTRAINT pk_students PRIMARY KEY (student_id)
);
-- Index names: students_m1_pkey (chosen by PostgreSQL) vs pk_students (chosen by me)
\d students_m1
\d students_m3

-- 2. Adding a primary key to an existing table
CREATE TABLE teachers (
    teacher_id INTEGER,
    name VARCHAR(100)
);
ALTER TABLE teachers ADD CONSTRAINT pk_teachers PRIMARY KEY (teacher_id);
\d teachers

-- 3. Single primary key
CREATE TABLE students (
    student_id SERIAL PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) UNIQUE,
    faculty VARCHAR(50)
);
