-- 4. Composite primary key
CREATE TABLE course_enrollments (
    student_id INTEGER,
    course_id INTEGER,
    semester VARCHAR(20),
    enrollment_date DATE DEFAULT CURRENT_DATE,
    grade CHAR(2),
    PRIMARY KEY (student_id, course_id, semester)
);
INSERT INTO course_enrollments (student_id, course_id, semester, grade) VALUES
(1, 101, '2024-Spring', 'A'),
(1, 102, '2024-Spring', 'B+'),
(2, 101, '2024-Spring', 'A-'),
(1, 101, '2024-Fall', 'A+');   -- same student and course, different semester: allowed
SELECT student_id, course_id, semester, grade FROM course_enrollments;
-- EXPECTED ERROR: the combination (1, 101, 2024-Spring) already exists
INSERT INTO course_enrollments (student_id, course_id, semester, grade)
VALUES (1, 101, '2024-Spring', 'C');

-- 5. AUTO_INCREMENT equivalents: SERIAL, BIGSERIAL, IDENTITY
CREATE TABLE products (
    product_id SERIAL PRIMARY KEY,
    product_name VARCHAR(100) NOT NULL,
    price DECIMAL(10,2)
);
CREATE TABLE transactions (
    transaction_id BIGSERIAL PRIMARY KEY,   -- can handle very large numbers
    amount DECIMAL(15,2),
    transaction_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE orders (
    order_id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(100),
    order_date DATE DEFAULT CURRENT_DATE
);
CREATE TABLE customers (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(100),
    email VARCHAR(150)
);
-- SERIAL = INTEGER NOT NULL DEFAULT nextval('products_product_id_seq')
\d products
-- GENERATED ALWAYS: PostgreSQL controls the value
INSERT INTO orders (customer_name) VALUES ('Aida');
-- EXPECTED ERROR: a value cannot be given manually
INSERT INTO orders (order_id, customer_name) VALUES (500, 'Timur');
SELECT order_id, customer_name FROM orders;
-- GENERATED BY DEFAULT: manual value allowed, otherwise generated
INSERT INTO customers (customer_id, customer_name, email)
VALUES (1000, 'VIP Customer', 'vip@example.com');
INSERT INTO customers (customer_name, email)
VALUES ('Regular Customer', 'regular@example.com');
