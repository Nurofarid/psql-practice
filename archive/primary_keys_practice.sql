-- Primary Keys practice
-- Run with: psql -d pk_practice -f primary_keys_practice.sql

DROP TABLE IF EXISTS students_m1, students_m2, students_m3, teachers, students,
  course_enrollments, products, transactions, orders, customers, departments;

-- Method 1: column-level
CREATE TABLE students_m1 (student_id INTEGER PRIMARY KEY, name VARCHAR(100), email VARCHAR(150));

-- Method 2: table-level
CREATE TABLE students_m2 (student_id INTEGER, name VARCHAR(100), email VARCHAR(150),
  PRIMARY KEY (student_id));

-- Method 3: named constraint
CREATE TABLE students_m3 (student_id INTEGER, name VARCHAR(100), email VARCHAR(150),
  CONSTRAINT pk_students PRIMARY KEY (student_id));

-- Adding a primary key to an existing table
CREATE TABLE teachers (teacher_id INTEGER, name VARCHAR(100));
ALTER TABLE teachers ADD CONSTRAINT pk_teachers PRIMARY KEY (teacher_id);

-- Single primary key (SERIAL)
CREATE TABLE students (
    student_id SERIAL PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) UNIQUE,
    faculty VARCHAR(50)
);
