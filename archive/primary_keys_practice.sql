-- SERIAL, BIGSERIAL, IDENTITY
CREATE TABLE products (product_id SERIAL PRIMARY KEY, product_name VARCHAR(100) NOT NULL,
  price DECIMAL(10,2));
CREATE TABLE transactions (transaction_id BIGSERIAL PRIMARY KEY, amount DECIMAL(15,2),
  transaction_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE orders (order_id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  customer_name VARCHAR(100), order_date DATE DEFAULT CURRENT_DATE);
CREATE TABLE customers (customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_name VARCHAR(100), email VARCHAR(150));

